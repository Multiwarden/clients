"""Generates the Multiwarden header logo: our vault mark plus the word "multiwarden"
("multi" bold, "warden" light) set in Open Sans (SIL Open Font License), as plain paths.

Run: python3 multiwarden/branding/generate-logo.py <OpenSans variable font .ttf>
Writes apps/browser/src/multiwarden/popup/multiwarden-logo.ts
"""
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from shapely.affinity import translate
from shapely.geometry import Point, Polygon, box
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps/browser/src/multiwarden/popup/multiwarden-logo.ts"
FONT = sys.argv[1]
HEIGHT = 45.0  # same viewBox height as the upstream logo


def instance(weight):
    return instantiateVariableFont(TTFont(FONT), {"wght": weight, "wdth": 100})


def text_path(font, text, x0, baseline, size):
    upm = font["head"].unitsPerEm
    s = size / upm
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    parts = []
    x = x0
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(gs)
        gs[name].draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        parts.append(pen.getCommands())
        x += hmtx[name][0] * s
    return " ".join(parts), x


def rounded_rect(x0, y0, x1, y1, r):
    return box(x0 + r, y0 + r, x1 - r, y1 - r).buffer(r, resolution=16)


def poly_to_path(geom):
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    out = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            out.append("M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z")
    return " ".join(out)


def mark(size):
    """The app icon as one colour: a rounded vault with the keyhole cut out."""
    u = size
    front = rounded_rect(0.0, 0.0, u, u, 0.22 * u)
    cx, cy = 0.5 * u, 0.5 * u
    head = Point(cx, cy - 0.08 * u).buffer(0.15 * u, resolution=24)
    stem = Polygon(
        [
            (cx - 0.075 * u, cy),
            (cx + 0.075 * u, cy),
            (cx + 0.125 * u, cy + 0.30 * u),
            (cx - 0.125 * u, cy + 0.30 * u),
        ]
    )
    return front.difference(unary_union([head, stem]))


def main():
    bold, light = instance(700), instance(330)
    size = 46.0  # font size so the x-height matches the upstream wordmark
    baseline = 34.0
    icon = 38.0
    front = translate(mark(icon), 0, (HEIGHT - icon) / 2 - 1.0)
    x = icon + 9
    multi, x = text_path(bold, "multi", x, baseline, size)
    warden, x = text_path(light, "warden", x + 0.5, baseline, size)
    width = round(x + 1)

    svg = (
        f'<svg viewBox="0 0 {width} {int(HEIGHT)}" xmlns="http://www.w3.org/2000/svg">\n'
        "    <title>Multiwarden</title>\n"
        f'    <path class="tw-fill-marketing-logo" fill-rule="evenodd" d="{poly_to_path(front)}"/>\n'
        f'    <path class="tw-fill-marketing-logo" d="{multi}"/>\n'
        f'    <path class="tw-fill-marketing-logo" d="{warden}"/>\n'
        "  </svg>"
    )
    OUT.write_text(
        'import { svg } from "@bitwarden/assets/svg";\n\n'
        "/**\n"
        " * Multiwarden: the header logo. Generated by multiwarden/branding/generate-logo.py\n"
        " * (Open Sans, SIL Open Font License); edit the script, not this file.\n"
        " */\n"
        f"export const MultiwardenLogo = svg`\n  {svg}\n`;\n"
    )
    Path("/tmp/logo/mw-logo.svg").write_text(svg.replace('class="tw-fill-marketing-logo"', 'fill="#fff"'))
    print("wrote", OUT, "width", width)


if __name__ == "__main__":
    main()
